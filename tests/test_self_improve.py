#!/usr/bin/env python3
from pathlib import Path
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

subprocess.run([sys.executable, str(ROOT / "workers" / "self_improve.py")], check=True)

score = json.loads((ROOT / "state" / "HARNESS_SCORECARD.json").read_text())
assert score["incident_count"] >= 1, score
assert score["learned_rule_count"] >= 1, score
assert score["wins"] + score["losses"] + score["blocked"] + score["open"] >= 1, score
assert score["release_receipt_verdict"] == "UNSET", score

win_loss = (ROOT / "state" / "WIN_LOSS_ANALYSIS.md").read_text()
rules = (ROOT / "state" / "AUTOGENERATED_RULES.md").read_text()
weird = (ROOT / "state" / "WEIRD_SALVAGE_INDEX.md").read_text()

assert "Win / Loss Analysis" in win_loss
assert "Auto-Generated Learned Rules" in rules
assert "No learned rules yet." not in rules
# A provisional prevention remains available, but must not be labelled a closed fix.
assert score["closed_incident_rule_count"] + score["unresolved_incident_prevention_count"] == score["learned_rule_count"], score
assert score["unresolved_incident_prevention_count"] >= 1, score
assert "## Closed-incident learned rules" in rules
assert "## Provisional prevention rules" in rules
assert "NOT VERIFIED AS FIXED" in rules
assert "LR-004" in rules  # Stable incident-rule identifiers are preserved

# A scheduled main observer has independently met LR-015's original stop
# condition. Keep this closure evidence and its strict proof scope intact:
# observer green is NOT repository reconciliation or live phone/runtime proof.
ledger = (ROOT / "state" / "INCIDENT_LEDGER.md").read_text(encoding="utf-8")
observer_incident = ledger.split(
    "### INCIDENT\nScheduled Foundation monitor reported expected access gaps as nightly workflow crashes\n", 1
)[1].split("\n### INCIDENT", 1)[0]
assert "- **VERDICT:** DONE" in observer_incident
assert "40556124576" in observer_incident
assert "ATTENTION_REQUIRED" in observer_incident
assert "Preview UNKNOWN" in observer_incident
assert "not repository drift" in observer_incident
assert score["closed_incident_rule_count"] >= 8, score

assert "Weird Salvage Index" in weird
# Guard the handoff that previously let FRIDAY's status lag new learning
# because GITHUB_TOKEN bot commits do not launch dependent workflows.
workflow = (ROOT / ".github/workflows/self-improve.yml").read_text(encoding="utf-8")
assert workflow.index("Sanitized generalized learning intake") < workflow.index("Refresh FRIDAY machine status from this learning pass")
assert workflow.index("Refresh FRIDAY machine status from this learning pass") < workflow.index("Record harness's own run")
assert "friday_control_plane.py build --observation" in workflow
assert "FRIDAY learning/status synchronization PASS" in workflow
assert "steps.friday_status.outcome" in workflow

print("Harness self-improvement worker PASS")
