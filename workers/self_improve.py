#!/usr/bin/env python3
"""Harness Card self-improvement worker.

Deterministically learns from outcomes and weird salvage.
Writes:
- state/HARNESS_SCORECARD.json
- state/WIN_LOSS_ANALYSIS.md
- state/AUTOGENERATED_RULES.md
- state/WEIRD_SALVAGE_INDEX.md
"""
from __future__ import annotations

import json
import re
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATE = ROOT / "state"
INCIDENTS = STATE / "INCIDENT_LEDGER.md"
WEIRD = STATE / "WEIRD_LEDGER.md"
CURRENT = STATE / "CURRENT_PROJECT.json"
RECEIPT = STATE / "RELEASE_RECEIPT.md"

FIELD_RE = re.compile(r"^- \*\*(.+?):\*\*\s*(.*)$")
INCIDENT_RE = re.compile(r"^### INCIDENT\s*$", re.M)
WEIRD_RE = re.compile(r"^### WEIRD\s*$", re.M)


def parse_blocks(text, marker_re, skip_title):
    starts = [m.start() for m in marker_re.finditer(text)]
    rows = []
    for n, start in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(text)
        block = text[start:end]
        lines = block.splitlines()
        title = ""
        for line in lines[1:]:
            if line.strip():
                title = line.strip()
                break
        fields = {}
        for line in lines:
            m = FIELD_RE.match(line.strip())
            if m:
                fields[m.group(1).strip().upper()] = m.group(2).strip()
        if title and title.lower() != skip_title.lower():
            rows.append({"title": title, **fields})
    return rows


def verdict_kind(v):
    u = (v or "").upper()
    if u.startswith("DONE"):
        return "win"
    if u.startswith("BLOCKED"):
        return "blocked"
    if u.startswith("FAILED"):
        return "loss"
    if u.startswith("RETIRED"):
        return "retired"
    return "open"


def is_user_facing(i):
    text = " ".join(str(v) for v in i.values()).lower()
    return any(
        x in text
        for x in (
            "user opened",
            "user observed",
            "user reported",
            "user-facing",
            "phone showed",
            "android",
        )
    )


def layers(i):
    return [x.strip() for x in i.get("LAYER", "").split("/") if x.strip()]


def rule_from(i):
    p = i.get("REGRESSION / PREVENTION", "").strip()
    if not p:
        return None
    return {
        "source": i["title"],
        "root_cause": i.get("ROOT CAUSE", "UNKNOWN"),
        "rule": p,
        "proof": i.get("REAL-WORLD PROOF", "UNKNOWN"),
        "incident_outcome": verdict_kind(i.get("VERDICT", "")),
    }


def receipt_verdict(text):
    m = re.search(r"^## VERDICT\s*\n([^\n]+)", text, re.M)
    if not m:
        return "UNKNOWN"
    value = m.group(1).strip()
    template_markers = ("DONE / BLOCKED", "<X>", "<Y>")
    if any(marker in value for marker in template_markers):
        return "UNSET"
    return value



def operator_outcome_summary(state: Path) -> dict:
    """Consume only bounded sanitized CI operator evidence, never raw chat.

    No rule is marked proven from a single run or from unverified claims.
    """
    path = state / "FRIDAY_OPERATOR_REPAIR_HISTORY.json"
    if not path.exists():
        return {"runs": 0, "repaired_runs": 0, "failed_repairs": 0,
                "retry_recovered_runs": 0, "verified_repeatable_repair": False}
    data = json.loads(path.read_text(encoding="utf-8"))
    if (not isinstance(data, dict) or data.get("schema_version") != "1.0.0"
            or data.get("privacy") != "SANITIZED_CI_OUTCOMES_ONLY"
            or not isinstance(data.get("runs"), list) or len(data["runs"]) > 50):
        raise ValueError("FRIDAY operator history is invalid or not sanitized")
    seen = set()
    successes = 0
    failures = 0
    recovered = 0
    for row in data["runs"]:
        if not isinstance(row, dict) or not isinstance(row.get("run_id"), str):
            raise ValueError("malformed operator history row")
        run_id = row["run_id"]
        if not run_id.isdecimal() or run_id in seen:
            raise ValueError("duplicate or invalid run ID in history")
        seen.add(run_id)
        action, verdict = row.get("action"), row.get("verdict")
        if action not in {"REPAIR_DERIVED_OWNER_STATUS", "TRIAGE_APPROVED_REF_DRIFT",
                          "VERIFY_EXISTING_MACHINE_CONTINUITY", "NONE"}:
            raise ValueError("unrecognized operator action in history")
        if not isinstance(verdict, str) or not verdict.startswith(("PASS_", "BLOCKED_", "FAILED_")):
            raise ValueError("unrecognized operator outcome in history")
        attempts = row.get("attempt_count")
        if type(attempts) is not int or attempts < 0 or attempts > 3:
            raise ValueError("invalid retry count in operator history")
        outcomes = row.get("attempt_outcomes")
        if not isinstance(outcomes, list) or len(outcomes) != attempts:
            raise ValueError("operator history attempt sequence does not match count")
        if not all(x in {"PASS_INDEPENDENT_RECHECK", "RETRYABLE_LOCAL_IO_FAILURE",
                         "FAILED_SEMANTIC_RECHECK", "BLOCKED_INVALID_STATE"} for x in outcomes):
            raise ValueError("unrecognized repair attempt outcome")
        if action == "REPAIR_DERIVED_OWNER_STATUS":
            if (verdict == "PASS_REPAIRED"
                    and row.get("proof") == "INDEPENDENT_SCORE_STATUS_RECHECK"
                    and outcomes and outcomes[-1] == "PASS_INDEPENDENT_RECHECK"):
                successes += 1
                if attempts > 1:
                    recovered += 1
            elif verdict == "FAILED_REPAIR":
                failures += 1
    return {"runs": len(seen), "repaired_runs": successes,
            "failed_repairs": failures, "retry_recovered_runs": recovered,
            "verified_repeatable_repair": successes >= 2}


def main():
    incidents = parse_blocks(
        INCIDENTS.read_text(encoding="utf-8"),
        INCIDENT_RE,
        "Short memorable name.",
    )
    weird = parse_blocks(
        WEIRD.read_text(encoding="utf-8"),
        WEIRD_RE,
        "Short memorable name.",
    )
    current = json.loads(CURRENT.read_text(encoding="utf-8"))
    receipt = RECEIPT.read_text(encoding="utf-8")

    # Fail closed when source ledgers visibly contain real entries but parsing returns none.
    # A learning system that silently learns zero from a populated ledger is itself a failure.
    incident_markers = len(INCIDENT_RE.findall(INCIDENTS.read_text(encoding="utf-8")))
    weird_markers = len(WEIRD_RE.findall(WEIRD.read_text(encoding="utf-8")))
    if incident_markers > 1 and not incidents:
        raise RuntimeError("incident ledger contains entries but parser recovered zero incidents")
    if weird_markers > 1 and not weird:
        raise RuntimeError("weird ledger contains entries but parser recovered zero weird items")

    operator_learning = operator_outcome_summary(STATE)
    kinds = Counter(verdict_kind(i.get("VERDICT", "")) for i in incidents)
    layer_counts = Counter(x for i in incidents for x in layers(i))
    user_cycles = sum(1 for i in incidents if is_user_facing(i))
    rules = [r for r in (rule_from(i) for i in incidents) if r]

    seen = set()
    unique = []
    for r in rules:
        k = re.sub(r"\s+", " ", r["rule"].lower()).strip(" .")
        if k not in seen:
            seen.add(k)
            unique.append(r)

    closed_rules = [r for r in unique if r["incident_outcome"] == "win"]
    open_rules = [r for r in unique if r["incident_outcome"] != "win"]

    score = {
        "schema_version": "1.2.0",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "active_project": current.get("active_project"),
        "evidence_state": current.get("evidence_state"),
        "incident_count": len(incidents),
        "wins": kinds["win"],
        "losses": kinds["loss"],
        "blocked": kinds["blocked"],
        "open": kinds["open"],
        "user_facing_failure_cycles_observed": user_cycles,
        "learned_rule_count": len(unique),
        "closed_incident_rule_count": len(closed_rules),
        "unresolved_incident_prevention_count": len(open_rules),
        "weird_salvage_count": len(weird),
        "friday_operator_learning": operator_learning,
        "top_failure_layers": layer_counts.most_common(),
        "release_receipt_verdict": receipt_verdict(receipt),
        "authority": current.get("authority", {}),
    }
    (STATE / "HARNESS_SCORECARD.json").write_text(
        json.dumps(score, indent=2) + "\n", encoding="utf-8"
    )

    analysis = [
        "# Win / Loss Analysis",
        "",
        "> AUTO-GENERATED. Do not hand-edit.",
        "",
        f"- Incidents: **{len(incidents)}**",
        f"- Wins: **{kinds['win']}**",
        f"- Losses: **{kinds['loss']}**",
        f"- Blocked/open: **{kinds['blocked'] + kinds['open']}**",
        f"- User-facing failure cycles: **{user_cycles}**",
        f"- Weird salvage items: **{len(weird)}**",
        f"- FRIDAY bounded operator runs observed: **{operator_learning['runs']}**",
        f"- Independently verified derived-status repairs: **{operator_learning['repaired_runs']}**",
        f"- Bounded repair attempts recovered after I/O retry: **{operator_learning['retry_recovered_runs']}**",
        f"- Failed derived-status repairs (require review): **{operator_learning['failed_repairs']}**",
        "",
    ]
    for n, i in enumerate(incidents, 1):
        analysis += [
            f"## {n}. {i['title']}",
            "",
            f"- **Outcome:** {i.get('VERDICT', 'UNKNOWN')}",
            f"- **What went wrong:** {i.get('SYMPTOM', 'UNKNOWN')}",
            f"- **Why it failed:** {i.get('ROOT CAUSE', 'UNKNOWN')}",
            f"- **What changed:** {i.get('FIX', 'UNKNOWN')}",
            f"- **Why the corrected path won:** {i.get('REAL-WORLD PROOF', 'UNKNOWN')}",
            f"- **Permanent lesson:** {i.get('REGRESSION / PREVENTION', 'UNKNOWN')}",
            "",
        ]
    (STATE / "WIN_LOSS_ANALYSIS.md").write_text(
        "\n".join(analysis), encoding="utf-8"
    )

    generated = [
        "# Auto-Generated Learned Rules",
        "",
        "> MACHINE-WRITTEN from the Incident Ledger. Preventive advice from unresolved incidents is kept but never represented as a verified fix.",
        "",
        "## Closed-incident learned rules",
        "",
        "An incident marked DONE contributed the following prevention rules. Its recorded proof applies only to the stated scope; this does not imply every downstream app is working.",
        "",
    ]
    for n, r in enumerate(unique, 1):
        if r["incident_outcome"] != "win":
            continue
        generated += [
            f"### LR-{n:03d} — {r['source']}",
            f"- **Incident closure:** DONE",
            f"- **Root cause learned:** {r['root_cause']}",
            f"- **Rule:** {r['rule']}",
            f"- **Evidence:** {r['proof']}",
            "",
        ]
    if not closed_rules:
        generated.append("- No closed-incident prevention rules yet.")
    generated += [
        "",
        "## Provisional prevention rules — original incident still unresolved",
        "",
        "These are protective hypotheses/checks from BLOCKED, FAILED, OPEN or RETIRED incidents. Use them to prevent harm, but do not claim the incident was fixed, the rule proven, or the target device validated.",
        "",
    ]
    for n, r in enumerate(unique, 1):
        if r["incident_outcome"] == "win":
            continue
        generated += [
            f"### LR-{n:03d} — {r['source']}",
            f"- **Incident closure:** {r['incident_outcome'].upper()} — NOT VERIFIED AS FIXED",
            f"- **Root cause learned:** {r['root_cause']}",
            f"- **Provisional prevention:** {r['rule']}",
            f"- **Evidence:** {r['proof']}",
            "",
        ]
    if not open_rules:
        generated.append("- No unresolved-incident prevention candidates.")
    repeated = [(k, v) for k, v in layer_counts.items() if v >= 2]
    if repeated:
        generated += ["", "## Repeated-layer escalations", ""]
        for k, v in repeated:
            generated.append(
                f"- **{k} repeated {v} times:** inspect sibling failure modes before another release touching this layer."
            )
    generated += [
        "",
        "## FRIDAY operator retry evidence — sanitized scheduled CI only",
        "",
        f"- Observed independent CI run identities: {operator_learning['runs']}",
        f"- Verified bounded repairs: {operator_learning['repaired_runs']}",
        f"- Recovered local I/O retry sequences: {operator_learning['retry_recovered_runs']}",
        f"- Failed repairs awaiting review: {operator_learning['failed_repairs']}",
    ]
    if operator_learning["verified_repeatable_repair"]:
        generated += [
            "- **REPEATABILITY VERIFIED (derived status only):** Two or more distinct scheduled runs successfully regenerated owner-readable status and passed independent scorefield checks. Reuse that bounded repair, never generalize it to source edits or live jobs.",
        ]
    else:
        generated += [
            "- **PROVISIONAL:** Do not call status repair repeatable until two distinct CI runs independently verify it.",
        ]
    if operator_learning["failed_repairs"]:
        generated += [
            "- **REVIEW NEEDED:** One or more bounded repairs failed; inspect exact sanitized stop reasons and improve a candidate test before expanding the repair menu.",
        ]
    generated += [
        "",
        "## Non-negotiable promotion rule",
        "",
        "Generated rules may strengthen proof and quality requirements. They may not remove privacy/safety boundaries, erase incident history, silently change the user's locked outcome, or promote proxy evidence to PROVEN_LIVE.",
        "",
    ]
    (STATE / "AUTOGENERATED_RULES.md").write_text(
        "\n".join(generated), encoding="utf-8"
    )

    salvage = [
        "# Weird Salvage Index",
        "",
        "> AUTO-GENERATED from WEIRD_LEDGER.md. Weird is preserved, not normalized away.",
        "",
    ]
    if not weird:
        salvage.append("- No weird salvage captured yet.")
    for n, w in enumerate(weird, 1):
        salvage += [
            f"## WS-{n:03d} — {w['title']}",
            "",
            f"- **Observed weird:** {w.get('OBSERVED', 'UNKNOWN')}",
            f"- **Why it was weird:** {w.get('WHY WEIRD', 'UNKNOWN')}",
            f"- **Potential value:** {w.get('POTENTIAL SALVAGE', 'UNKNOWN')}",
            f"- **Origin:** {w.get('ORIGIN', 'UNKNOWN')}",
            f"- **Do not lose:** {w.get('PRESERVE', 'YES')}",
            "",
        ]
    (STATE / "WEIRD_SALVAGE_INDEX.md").write_text(
        "\n".join(salvage), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
